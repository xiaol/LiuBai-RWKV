#!/usr/bin/env python3
"""Export generated cursor-LM clips from several vae/eval_cursor_lm.py runs (same --n/--seed crops) as MP3 + a browser player.

Only model outputs are exported (C_<cond>.flac); the original excerpts (A_original) and VAE reconstructions (B_vae) of the
commercial test songs, and their lyric text, stay local. Clips 0..n-1 in eval order (not cherry-picked).
usage: export_cursor_samples.py --out samples/cursor_cfg_20261026 --n 12 \
         --run "v2 CFG 1=out/clm_eval/cursor1_25k_causal96" --run "v4 CFG 3=out/clm_eval/cursor_v4_40k_c96_cfg3" ...
"""
import argparse, html, json, statistics as st
from pathlib import Path
import soundfile as sf


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--out", required=True); ap.add_argument("--n", type=int, default=12)
    ap.add_argument("--run", action="append", required=True, help="label=eval dir"); ap.add_argument("--conds", default="own,swap")
    ap.add_argument("--title", default="LiuBai-RWKV cursor LM: lyric CFG, v2 vs v4 latent")
    a = ap.parse_args(); out = Path(a.out); out.mkdir(parents=True, exist_ok=True); conds = a.conds.split(",")
    runs = []
    for spec in a.run:
        label, d = spec.split("=", 1); rows = json.load(open(Path(d) / "eval.json"))["rows"]; runs.append((label, Path(d), rows))
    ref = [r["own"] for r in runs[0][2]]
    for label, d, rows in runs: assert [r["own"] for r in rows] == ref, f"{d}: different crops"
    slug = lambda s: "".join(c if c.isalnum() else "_" for c in s.lower()).strip("_")
    summary = {}
    for label, d, rows in runs:
        summary[label] = {c: st.median(r[f"cer_C_{c}"] for r in rows) for c in conds if f"cer_C_{c}" in rows[0]}
        if "swap" in summary[label]: summary[label]["swap"] = st.median(r["cer_C_swap_given"] for r in rows)
    clips = []
    for k in range(a.n):
        cl = []
        for label, d, rows in runs:
            for c in conds:
                src = d / f"{k:03d}" / f"C_{c}.flac"
                if not src.exists(): continue
                y, sr = sf.read(src); name = f"{k:03d}_{slug(label)}_{c}.mp3"; sf.write(out / name, y, sr, format="MP3")
                cer = rows[k]["cer_C_swap_given" if c == "swap" else f"cer_C_{c}"]
                cl.append(dict(label=label, cond=c, file=name, cer=round(cer, 3)))
        clips.append(dict(k=k, letters=len(ref[k]), clips=cl))
    json.dump(dict(runs={l: str(d) for l, d, _ in runs}, median_cer=summary, clips=clips), open(out / "index.json", "w"), indent=1)
    H = [f"""<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>{html.escape(a.title)}</title><style>
body{{font:15px/1.45 system-ui,sans-serif;max-width:1000px;margin:2rem auto;padding:0 1rem;color:#222;background:#fafafa}}
.clip{{background:#fff;border:1px solid #e3e3e3;border-radius:8px;padding:.6rem 1rem;margin:.8rem 0}}
.grid{{display:grid;grid-template-columns:repeat(auto-fill,minmax(300px,1fr));gap:.5rem}} .grid div{{font-size:.9em}}
audio{{width:100%}} table{{border-collapse:collapse}} td,th{{border:1px solid #ddd;padding:.2rem .6rem;text-align:right}}
</style></head><body><h1>{html.escape(a.title)}</h1>
<p>Held-out real songs, 4 s real prompt (encoded from its own audio only), 20 s generated by the block-flow RWKV cursor LM.
<b>own</b> = given the clip's own lyrics, <b>swap</b> = given another clip's lyrics (does it sing what it is told?).
Number = Whisper letter CER against the lyrics it was given (lower is better; the original recordings score 0.43 median).
Only generated audio is published; the prompts and originals are commercial recordings.</p>
<table><tr><th>run</th>""" + "".join(f"<th>median CER {c}</th>" for c in conds) + "</tr>"]
    for label, s in summary.items():
        H.append(f"<tr><th>{html.escape(label)}</th>" + "".join(f"<td>{s[c]:.3f}</td>" if c in s else "<td>-</td>" for c in conds) + "</tr>")
    H.append("</table>")
    for c in clips:
        H.append(f'<div class="clip"><b>clip {c["k"]:03d}</b> ({c["letters"]} letters of lyrics)<div class="grid">')
        for x in c["clips"]:
            H.append(f'<div>{html.escape(x["label"])}, {x["cond"]}: CER {x["cer"]:.2f}<audio controls preload="none" src="{x["file"]}"></audio></div>')
        H.append("</div></div>")
    H.append("</body></html>"); (out / "player.html").write_text("\n".join(H), encoding="utf-8")
    print(out, len(clips), "clips", sum(len(c["clips"]) for c in clips), "files", summary)


if __name__ == "__main__":
    main()
